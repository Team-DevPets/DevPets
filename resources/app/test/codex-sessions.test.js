const test = require('node:test')
const assert = require('node:assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { createCodexSessionWatcher } = require('../codex-sessions')

// 실제 기록과 같은 모양의 줄 (내용은 가짜)
const meta = (extra = {}) => JSON.stringify({ timestamp: '2026-10-22T03:00:00.000Z', type: 'session_meta', payload: { id: 't1', originator: 'Codex Desktop', source: 'vscode', thread_source: 'user', base_instructions: 'x'.repeat(70000), ...extra } })
const ev = (iso, payload) => JSON.stringify({ timestamp: iso, type: 'event_msg', payload })
const started = (iso, turn) => ev(iso, { type: 'task_started', turn_id: turn, started_at: Math.floor(Date.parse(iso) / 1000) })
const item = (iso, turn, kind) => ev(iso, { type: 'item_completed', turn_id: turn, item: { type: kind, aggregated_output: 'y'.repeat(5000) } })
const complete = (iso, turn, ms) => ev(iso, { type: 'task_complete', turn_id: turn, completed_at: Math.floor(Date.parse(iso) / 1000), duration_ms: ms, last_agent_message: '비밀 내용' })
const aborted = (iso, turn) => ev(iso, { type: 'turn_aborted', turn_id: turn, reason: 'interrupted' })

function setup() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'codex-sessions-'))
  const day = path.join(root, '2026', '10', '22')
  fs.mkdirSync(day, { recursive: true })
  let clock = Date.parse('2026-10-22T03:00:10.000Z')
  const w = createCodexSessionWatcher({ root, now: () => clock })
  return { root, day, w, tick: ms => (clock += ms), setClock: iso => (clock = Date.parse(iso)) }
}
const write = (file, lines) => fs.appendFileSync(file, lines.map(l => l + '\n').join(''))

test('작업 시작 → 단계 → 완료를 따라간다', () => {
  const { day, w, setClock } = setup()
  const file = path.join(day, 'rollout-a.jsonl')
  write(file, [meta()])
  w.scan()
  assert.deepStrictEqual(w.entries(), [])
  write(file, [started('2026-10-22T03:00:01.000Z', 'u1')])
  w.poll()
  let e = w.entries()
  assert.strictEqual(e.length, 1)
  assert.strictEqual(e[0].mood, 'working')
  assert.strictEqual(e[0].source, 'Codex 앱')
  write(file, [item('2026-10-22T03:00:03.000Z', 'u1', 'CommandExecution')])
  w.poll()
  assert.strictEqual(w.entries()[0].detail, '명령 실행')
  write(file, [complete('2026-10-22T03:00:20.000Z', 'u1', 19000)])
  setClock('2026-10-22T03:00:21.000Z')
  w.poll()
  e = w.entries()
  assert.strictEqual(e[0].mood, 'done')
  assert.strictEqual(e[0].duration, 19000)
  assert.ok(!JSON.stringify(e).includes('비밀'), '대화 내용은 내보내지 않는다')
})

test('중단하면 쉬는 중으로', () => {
  const { day, w } = setup()
  const file = path.join(day, 'rollout-b.jsonl')
  write(file, [meta(), started('2026-10-22T03:00:01.000Z', 'u1')])
  w.scan()
  assert.strictEqual(w.entries()[0].mood, 'working')
  write(file, [aborted('2026-10-22T03:00:05.000Z', 'u1')])
  w.poll()
  assert.deepStrictEqual(w.entries(), [])
})

test('하위 에이전트(guardian) 스레드는 무시한다', () => {
  const { day, w } = setup()
  write(path.join(day, 'rollout-g.jsonl'), [meta({ source: { subagent: { other: 'guardian' } }, thread_source: 'guardian_review' }), started('2026-10-22T03:00:01.000Z', 'g1')])
  w.scan()
  assert.deepStrictEqual(w.entries(), [])
  assert.strictEqual(w.info().files, 0)
})

test('반쯤 쓰인 줄은 다 쓰인 뒤에 읽는다', () => {
  const { day, w } = setup()
  const file = path.join(day, 'rollout-c.jsonl')
  write(file, [meta()])
  w.scan()
  const line = started('2026-10-22T03:00:01.000Z', 'u1')
  fs.appendFileSync(file, line.slice(0, 30))
  w.poll()
  assert.deepStrictEqual(w.entries(), [])
  fs.appendFileSync(file, line.slice(30) + '\n')
  w.poll()
  assert.strictEqual(w.entries()[0].mood, 'working')
})

test('큰 기존 파일은 끝부분만 읽고 지금 상태를 잡는다', () => {
  const { day, w } = setup()
  const file = path.join(day, 'rollout-big.jsonl')
  const lines = [meta()]
  for (let i = 0; i < 300; i++) lines.push(item('2026-10-22T02:00:00.000Z', 'old', 'CommandExecution'))
  lines.push(complete('2026-10-22T02:10:00.000Z', 'old', 1000))
  lines.push(started('2026-10-22T03:00:02.000Z', 'u2'))
  lines.push(item('2026-10-22T03:00:04.000Z', 'u2', 'FileChange'))
  write(file, lines)
  assert.ok(fs.statSync(file).size > 1024 * 1024)
  w.scan()
  const e = w.entries()
  assert.strictEqual(e.length, 1)
  assert.strictEqual(e[0].mood, 'working')
  assert.strictEqual(e[0].detail, '파일 고치기')
})

test('완료는 5분 뒤 사라지고, 오래 멈춘 진행 중 작업은 버린다', () => {
  const { day, w, setClock } = setup()
  const a = path.join(day, 'rollout-d.jsonl')
  write(a, [meta(), started('2026-10-22T03:00:01.000Z', 'u1'), complete('2026-10-22T03:00:09.000Z', 'u1', 8000)])
  w.scan()
  assert.strictEqual(w.entries()[0].mood, 'done')
  setClock('2026-10-22T03:06:00.000Z')
  assert.deepStrictEqual(w.entries(), [])
  const b = path.join(day, 'rollout-e.jsonl')
  write(b, [meta(), started('2026-10-22T03:06:00.000Z', 'u9')])
  fs.utimesSync(b, new Date('2026-10-22T03:06:00.000Z'), new Date('2026-10-22T03:06:00.000Z'))
  w.scan()
  assert.strictEqual(w.entries()[0].mood, 'working')
  setClock('2026-10-22T03:40:00.000Z')
  w.poll()
  assert.deepStrictEqual(w.entries(), [])
})

test('기록 폴더가 없어도 오류 없이 비어 있다', () => {
  const w = createCodexSessionWatcher({ root: path.join(os.tmpdir(), 'no-such-codex-' + process.pid) })
  w.scan(); w.poll()
  assert.deepStrictEqual(w.entries(), [])
  assert.strictEqual(w.info().rootFound, false)
})
